import '../models/prayer_settings.dart';

/// A small, curated city catalogue for manual selection. It is intentionally
/// not a default: the user must explicitly pick a city.
class CityInfo {
  const CityInfo({
    required this.name,
    required this.country,
    required this.latitude,
    required this.longitude,
    required this.timezoneId,
    required this.suggestedMethod,
    this.arabicName,
  });

  final String name;
  final String country;
  final String? arabicName;
  final double latitude;
  final double longitude;
  final String timezoneId;
  final PrayerCalculationMethod suggestedMethod;

  String get searchText =>
      '$name ${arabicName ?? ''} $country'.toLowerCase();

  GeoLocation toLocation() => GeoLocation(
        name: name,
        country: country,
        latitude: latitude,
        longitude: longitude,
        timezoneId: timezoneId,
        suggestedMethod: suggestedMethod,
      );
}

