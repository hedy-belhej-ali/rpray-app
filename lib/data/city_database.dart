List<CityInfo> searchCities(String query) {
  final normalized = query.trim().toLowerCase();
  if (normalized.isEmpty) return cityDatabase;
  return cityDatabase
      .where((city) => city.searchText.contains(normalized))
      .toList(growable: false);
}
